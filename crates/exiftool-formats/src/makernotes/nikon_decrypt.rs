/// Decrypt a Nikon data block. Symmetric (encrypt == decrypt).
///
/// `start` is ExifTool `DecryptStart` (prefix stays plaintext).
pub fn decrypt(data: &[u8], start: usize, serial: u32, shutter_count: u32) -> Vec<u8> {
    let mut out = data.to_vec();
    let mut d = Decryptor::new(serial, shutter_count);
    let len = out.len().saturating_sub(start);
    d.apply(&mut out, start, len);
    out
}

/// Stateful Nikon decrypt (`Nikon.pm` `Decrypt`).
///
/// After the first range with keys, later `apply` calls without a new `Decryptor`
/// jump the cipher to `start` using the closed-form `cj`/`ck` (piecewise `NIKON_OFFSETS`).
pub struct Decryptor {
    ci0: u32,
    cj0: u32,
    ck0: u32,
    decrypt_start: Option<usize>,
}

impl Decryptor {
    pub fn new(serial: u32, shutter_count: u32) -> Self {
        let mut key = 0u32;
        for i in 0..4 {
            key ^= (shutter_count >> (i * 8)) & 0xff;
        }
        Self {
            ci0: u32::from(XLAT0[(serial & 0xff) as usize]),
            cj0: u32::from(XLAT1[(key & 0xff) as usize]),
            ck0: 0x60,
            decrypt_start: None,
        }
    }

    /// XOR `data[start..start+len]` in place (clipped to `data.len()`).
    pub fn apply(&mut self, data: &mut [u8], start: usize, len: usize) {
        if start >= data.len() || len == 0 {
            return;
        }
        let len = len.min(data.len() - start);
        let (mut cj, mut ck) = if let Some(ds) = self.decrypt_start {
            let n = start.saturating_sub(ds) as u64;
            let tri = n.saturating_mul(n.saturating_sub(1)) / 2;
            let inner = n.wrapping_mul(u64::from(self.ck0)).wrapping_add(tri);
            let cj =
                (u64::from(self.cj0).wrapping_add(u64::from(self.ci0).wrapping_mul(inner))) & 0xff;
            let ck = (u64::from(self.ck0).wrapping_add(n)) & 0xff;
            (cj as u32, ck as u32)
        } else {
            self.decrypt_start = Some(start);
            (self.cj0, self.ck0)
        };
        for b in &mut data[start..start + len] {
            cj = (cj.wrapping_add(self.ci0.wrapping_mul(ck))) & 0xff;
            ck = (ck + 1) & 0xff;
            *b ^= cj as u8;
        }
    }
}

/// Piecewise decrypt a `NIKON_OFFSETS` ShotInfo block (`PrepareNikonOffsets`, mode 0).
///
/// Decrypts `[decrypt_start, offset_table+4)`, the offset table, then each non-zero
/// section up to the next offset (or EOF). Returns `NumberOffsets`.
pub fn prepare_nikon_offsets(
    data: &mut [u8],
    decrypt_start: usize,
    offset_table: usize,
    big_endian: bool,
    serial: u32,
    shutter_count: u32,
) -> Option<u32> {
    if offset_table + 4 > data.len() || offset_table < decrypt_start {
        return None;
    }
    let mut dec = Decryptor::new(serial, shutter_count);
    let dpos = offset_table + 4;
    dec.apply(data, decrypt_start, dpos - decrypt_start);
    let num = read_u32(data, offset_table, big_endian)?;
    if num > 256 {
        return None;
    }
    let more = num as usize * 4;
    if offset_table + 4 + more > data.len() {
        return None;
    }
    dec.apply(data, dpos, more);
    let mut offs: Vec<u32> = Vec::new();
    for i in 0..num as usize {
        let pos = offset_table + 4 + 4 * i;
        let off = read_u32(data, pos, big_endian)?;
        if off != 0 {
            offs.push(off);
        }
    }
    offs.sort_unstable();
    offs.push(data.len() as u32);
    for w in offs.windows(2) {
        let start = w[0] as usize;
        let end = w[1] as usize;
        if start >= data.len() || end <= start {
            continue;
        }
        dec.apply(data, start, end - start);
    }
    Some(num)
}

fn read_u32(data: &[u8], off: usize, big_endian: bool) -> Option<u32> {
    let b = data.get(off..off + 4)?;
    let arr = [b[0], b[1], b[2], b[3]];
    Some(if big_endian {
        u32::from_be_bytes(arr)
    } else {
        u32::from_le_bytes(arr)
    })
}

/// Serial number string to decrypt key (ExifTool `SerialKey`).
pub fn serial_key(serial: &str, model: Option<&str>) -> u32 {
    let s = serial.trim_end_matches(char::from(0)).trim();
    if !s.is_empty() && s.bytes().all(|c| c.is_ascii_digit()) {
        return s.parse().unwrap_or(0);
    }
    if model.is_some_and(|m| m.trim_end().ends_with("D50")) {
        return 0x22;
    }
    0x60
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn decrypt_exiftool_vector() {
        let data = decrypt(&0x34a290d3u32.to_be_bytes(), 0, 0x1234_5678, 0x0000_0123);
        let got = u32::from_be_bytes(data.try_into().unwrap());
        assert_eq!(got, 0xcae17d2f);
    }

    #[test]
    fn piecewise_jump_matches_contiguous() {
        let mut plain = vec![0u8; 180];
        for (i, b) in plain.iter_mut().enumerate() {
            *b = (i % 251) as u8;
        }
        let serial = 0x1234_5678;
        let count = 0x0000_0123;
        let full = decrypt(&plain, 4, serial, count);
        let mut jump = plain.clone();
        let mut d = Decryptor::new(serial, count);
        d.apply(&mut jump, 4, 40);
        d.apply(&mut jump, 100, 16);
        assert_eq!(&jump[100..116], &full[100..116]);
        assert_eq!(&jump[4..44], &full[4..44]);
        assert_eq!(&jump[0..4], &plain[0..4]);
    }

    #[test]
    fn nikon_offsets_recovers_section() {
        let mut plain = vec![0u8; 200];
        plain[0..4].copy_from_slice(b"0245");
        plain[4..8].copy_from_slice(b"1.00");
        plain[0x24..0x28].copy_from_slice(&2u32.to_le_bytes());
        plain[0x28..0x2c].copy_from_slice(&120u32.to_le_bytes());
        plain[0x2c..0x30].copy_from_slice(&160u32.to_le_bytes());
        plain[120..124].copy_from_slice(b"ABCD");
        plain[160..164].copy_from_slice(b"EFGH");
        let serial = 7;
        let count = 99;
        let mut cipher = decrypt(&plain, 4, serial, count);
        let n = prepare_nikon_offsets(&mut cipher, 4, 0x24, false, serial, count).unwrap();
        assert_eq!(n, 2);
        assert_eq!(&cipher[0..4], b"0245");
        assert_eq!(&cipher[120..124], b"ABCD");
        assert_eq!(&cipher[160..164], b"EFGH");
        assert_eq!(&cipher[4..8], b"1.00");
    }
}
